"""
Generate Rust reduce-bend GPKG test data from tests/reduce_bend_unittest.py.

This mirrors the simplify migration pattern:
- input GPKG per case
- expected-output GPKG per case (generated by Python reference algorithm)
- manifest JSON consumed by Rust integration tests

Usage (QGIS Python environment):
    python generate_test_reduce_bend_gpkg.py

Outputs:
    tests/bend/test_rb_XX_input.gpkg
    tests/bend/test_rb_XX_expected.gpkg
    tests/bend/test_manifest_reduce_bend.json
"""

